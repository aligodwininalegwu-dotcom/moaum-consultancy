import path from "node:path";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import { ALLOWED_UPLOAD_TYPES, MAX_UPLOAD_BYTES, MAX_UPLOAD_LABEL } from "@/lib/constants";

/**
 * Application documents are stored in Vercel Blob when BLOB_READ_WRITE_TOKEN
 * is set (production), otherwise in a local folder outside /public.
 * Either way, files are only ever served through /api/files, which checks
 * that the viewer owns the application or is staff.
 */

const UPLOAD_DIR = path.resolve(process.cwd(), process.env.UPLOAD_DIR ?? "uploads");
const useBlob = () => Boolean(process.env.BLOB_READ_WRITE_TOKEN);

const EXT: Record<string, string> = {
  "application/pdf": "pdf",
  "image/jpeg": "jpg",
  "image/png": "png",
};

export function validateUpload(file: unknown, label: string, required = true): string | null {
  if (!(file instanceof File) || file.size === 0) return required ? `${label} is required` : null;
  if (!ALLOWED_UPLOAD_TYPES.includes(file.type)) return `${label} must be a PDF, JPG or PNG file`;
  if (file.size > MAX_UPLOAD_BYTES) return `${label} must be ${MAX_UPLOAD_LABEL} or smaller`;
  return null;
}

/** Saves an uploaded file and returns the value to store in the database. */
export async function saveUpload(file: File, prefix: string) {
  const name = `${prefix}-${randomUUID()}.${EXT[file.type] ?? "bin"}`;

  if (useBlob()) {
    const { put } = await import("@vercel/blob");
    // The random UUID plus Blob's own random suffix make the URL unguessable;
    // it is never sent to the browser (downloads are proxied by /api/files).
    const blob = await put(`applications/${name}`, file, { access: "public", contentType: file.type, addRandomSuffix: true });
    return blob.url;
  }

  await mkdir(UPLOAD_DIR, { recursive: true });
  await writeFile(path.join(UPLOAD_DIR, name), Buffer.from(await file.arrayBuffer()));
  return name;
}

export async function readUpload(stored: string) {
  if (stored.startsWith("https://")) {
    // Only fetch from Vercel Blob, never from an arbitrary stored URL.
    const url = new URL(stored);
    if (!url.hostname.endsWith(".blob.vercel-storage.com")) return null;
    const res = await fetch(url, { cache: "no-store" });
    if (!res.ok) return null;
    return { data: Buffer.from(await res.arrayBuffer()), type: res.headers.get("content-type") ?? "application/octet-stream" };
  }

  // Stored names are generated by saveUpload; reject anything path-like.
  if (!/^[\w-]+\.(pdf|jpg|png)$/.test(stored)) return null;
  try {
    const data = await readFile(path.join(UPLOAD_DIR, stored));
    const ext = stored.split(".").pop()!;
    const type = Object.entries(EXT).find(([, e]) => e === ext)?.[0] ?? "application/octet-stream";
    return { data, type };
  } catch {
    return null;
  }
}

/** File extension for download names, for both local names and Blob URLs. */
export function storedExtension(stored: string) {
  return new URL(stored, "file:///").pathname.split(".").pop() ?? "bin";
}
