import path from "node:path";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import { ALLOWED_UPLOAD_TYPES, MAX_UPLOAD_BYTES } from "@/lib/constants";

const UPLOAD_DIR = path.resolve(process.cwd(), process.env.UPLOAD_DIR ?? "uploads");

const EXT: Record<string, string> = {
  "application/pdf": "pdf",
  "image/jpeg": "jpg",
  "image/png": "png",
};

export function validateUpload(file: unknown, label: string, required = true): string | null {
  if (!(file instanceof File) || file.size === 0) return required ? `${label} is required` : null;
  if (!ALLOWED_UPLOAD_TYPES.includes(file.type)) return `${label} must be a PDF, JPG or PNG file`;
  if (file.size > MAX_UPLOAD_BYTES) return `${label} must be 5 MB or smaller`;
  return null;
}

/** Saves an uploaded file outside /public and returns its stored file name. */
export async function saveUpload(file: File, prefix: string) {
  await mkdir(UPLOAD_DIR, { recursive: true });
  const name = `${prefix}-${randomUUID()}.${EXT[file.type] ?? "bin"}`;
  await writeFile(path.join(UPLOAD_DIR, name), Buffer.from(await file.arrayBuffer()));
  return name;
}

export async function readUpload(name: string) {
  // Stored names are generated by saveUpload; reject anything path-like.
  if (!/^[\w-]+\.(pdf|jpg|png)$/.test(name)) return null;
  try {
    const data = await readFile(path.join(UPLOAD_DIR, name));
    const ext = name.split(".").pop()!;
    const type = Object.entries(EXT).find(([, e]) => e === ext)?.[0] ?? "application/octet-stream";
    return { data, type };
  } catch {
    return null;
  }
}
